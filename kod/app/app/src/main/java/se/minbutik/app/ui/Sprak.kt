/**
 * Appens språk: svenska (sv) eller arabiska (ar, höger till vänster). Texterna skrivs på svenska i koden
 * och t("…") ger den arabiska översättningen när arabiska är valt. Saknas en översättning visas svenskan.
 * Butikens egna svar (chatten i Ny annons) kommer från Pi:n och översätts där (Accept-Language).
 */
object Sprak {
    var kod by mutableStateOf("sv")
    val arabiska get() = kod == "ar"
}

fun t(sv: String): String = if (Sprak.kod == "ar") AR[sv] ?: sv else sv

/** Svensk text (pris, namn, datum) inne i arabisk text: håll den vänster-till-höger ("15 kr/kg", inte "kr/kg 15"). */
fun ltr(s: String): String = if (Sprak.kod == "ar" && s.isNotEmpty()) "⁦$s⁩" else s

/** t med %s-platser: tf("Skriv ut %s", 3). */
fun tf(sv: String, vararg varden: Any?): String = t(sv).format(*varden.map { if (it is String) ltr(it) else it }.toTypedArray())

